/**
 * The app runs inside Home Assistant's ingress iframe on HA's own origin, so it can read the
 * language of the HA frontend (per user) from the parent document. `?lang=` overrides for testing.
 */
function detectLang(): Lang {
  const candidates: Array<string | null | undefined> = [];
  try {
    candidates.push(new URLSearchParams(window.location.search).get('lang'));
  } catch {
    // ignore
  }
  try {
    if (window.parent !== window) candidates.push(window.parent.document.documentElement.lang);
  } catch {
    // Cross-origin parent (not inside HA) – fall through to the browser language.
  }
  try {
    const selected = window.localStorage.getItem('selectedLanguage');
    if (selected) candidates.push(JSON.parse(selected));
  } catch {
    // ignore
  }
  candidates.push(...(navigator.languages ?? []), navigator.language);
  const first = candidates.find((c) => typeof c === 'string' && c.trim() !== '');
  return first?.toLowerCase().startsWith('de') ? 'de' : 'en';
}

