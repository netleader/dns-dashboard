const dict: Record<Key, string> = lang === 'de' ? de : en;

export function t(key: Key, params?: Record<string, string | number>): string {
  const s = dict[key] ?? en[key] ?? key;
  return params ? s.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? `{${k}}`)) : s;
}

/** Translates keys that come from data (reasons, list names) and falls back to the raw value. */
export function tMaybe(key: string, fallback: string, params?: Record<string, string | number>): string {
  return key in dict ? t(key as Key, params) : fallback;
}
